import assert from 'node:assert/strict';
import test from 'node:test';
import { inspectArchitecture } from '../scripts/architecture.mts';

test('expected-error directives cannot bypass strict source checking',()=>{
  const errors=inspectArchitecture({'src/domain/example.ts':'// @ts-expect-error\nexport const value: number = "bad";'});
  assert.ok(errors.some(error=>error.includes('@ts-expect-error')));
});

test('valid layers resolve TS, JS and extensionless imports plus content data', () => {
  assert.deepEqual(inspectArchitecture({
    'src/content/types.ts': 'export type Item = { name: string };',
    'src/content/data.ts': "import data from '../../content/items/a.json'; import { z } from 'zod';",
    'src/domain/state.ts': "import type {Item} from '../content/types.js';",
    'src/platform/input/mapping.ts': 'export const ACTIONS = [];',
    'src/platform/input/devices.ts': 'export interface Device {}',
    'src/rendering/view.ts': "import '../domain/state';",
    'src/ui/menu.ts': "import {ACTIONS} from '../platform/input/mapping'; import type {Device} from '../platform/input/devices';",
    'src/app/main.ts': "import '../ui/menu'; import '../rendering/view.ts';",
  }), []);
});

test('forbidden import direction and runtime UI browser adapter dependencies fail', () => {
  const errors = inspectArchitecture({
    'src/domain/state.ts': "import '../ui/menu';",
    'src/ui/menu.ts': "import '../platform/input/devices';",
    'src/platform/input/devices.ts': 'export {}',
  });
  assert.ok(errors.some(error => error.includes('domain/state.ts') && error.includes('dependency')));
  assert.ok(errors.some(error => error.includes('ui/menu.ts') && error.includes('dependency')));
});

test('type-only dependencies participate in cycle detection', () => {
  const errors = inspectArchitecture({
    'src/domain/a.ts': "import type {B} from './b.js'; export type A = B;",
    'src/domain/b.ts': "export type {A as B} from './a';",
  });
  assert.ok(errors.some(error => error.includes('cycle')));
});

test('module length is enforced except for generated content manifest size', () => {
  assert.ok(inspectArchitecture({ 'src/app/huge.ts': '// line\n'.repeat(351) }).some(error => error.includes('350')));
  assert.deepEqual(inspectArchitecture({ 'src/content/manifest.ts': '// Generated by content script\n' + '// line\n'.repeat(351) }), []);
  assert.ok(inspectArchitecture({ 'src/app/huge.ts': '// Generated\n' + '// line\n'.repeat(351) }).some(error => error.includes('350')));
});

test('type and execution bypasses fail even in generated sources', () => {
  const files = {
    'src/content/manifest.ts': '// Generated by script\nlet value: any; // @ts-ignore\neval(value); new Function(value); import(value);',
    'src/app/unsafe.js': 'export const x = 1;',
    'src/unknown/x.ts': '// @ts-nocheck\nexport {};',
  };
  const errors = inspectArchitecture(files).join('\n');
  for (const violation of ['explicit any', '@ts-ignore', '@ts-nocheck', 'eval', 'Function', 'nonliteral', 'JavaScript', 'unknown layer']) assert.ok(errors.includes(violation), violation);
});

test('domain and content reject browser identifiers while permitting ordinary property names', () => {
  const errors = inspectArchitecture({
    'src/domain/bad.ts': 'const x = window.location; const y = document.title; navigator.getGamepads(); localStorage.clear();',
    'src/content/good.ts': 'const x = {window: 1}; export const y = x.window;',
  });
  assert.equal(errors.filter(error => error.includes('browser global')).length, 4);
  assert.ok(errors.every(error => error.includes('domain/bad.ts')));
});

test('unresolved and out-of-source dependencies cannot bypass layer rules', () => {
  const errors = inspectArchitecture({
    'src/app/main.ts': "import '../missing'; import '../../game.js'; import 'unknown-package';",
  });
  assert.ok(errors.length >= 3);
});

test('qualified dynamic execution and import-equals cannot bypass guards', () => {
  const errors = inspectArchitecture({
    'src/app/main.ts': "globalThis.eval('x'); new globalThis.Function('x'); import lib = require('../domain/state');",
    'src/domain/state.ts': 'export const state = 1;',
  }).join('\n');
  assert.ok(errors.includes('eval execution'));
  assert.ok(errors.includes('Function execution'));
  assert.ok(errors.includes('import-equals'));
});

test('comment directives inside strings remain ordinary data', () => {
  assert.deepEqual(inspectArchitecture({ 'src/content/text.ts': "export const data = '@ts-ignore any eval(window)';" }), []);
});
